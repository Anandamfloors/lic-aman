<?php
declare(strict_types=1);
header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store, max-age=0');
header('X-Content-Type-Options: nosniff');

function respond(int $status, array $body): never {
    http_response_code($status);
    echo json_encode($body, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}
if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') {
    header('Allow: POST');
    respond(405, ['success' => false, 'message' => 'Only POST requests are accepted.']);
}
$contentType = strtolower((string)($_SERVER['CONTENT_TYPE'] ?? ''));
if (strpos($contentType, 'application/json') === false) {
    respond(415, ['success' => false, 'message' => 'Invalid form request. Please refresh and try again.']);
}
$raw = file_get_contents('php://input');
$data = json_decode($raw ?: '', true);
if (!is_array($data)) respond(400, ['success' => false, 'message' => 'Invalid form data. Please try again.']);

// Honeypot: silently reject bots without sending email.
if (trim((string)($data['botcheck'] ?? '')) !== '') respond(200, ['success' => true]);

function clean_line(mixed $value, int $max = 300): string {
    $value = trim((string)$value);
    $value = preg_replace('/[\r\n\x00-\x1F\x7F]+/u', ' ', $value) ?? '';
    return mb_substr($value, 0, $max, 'UTF-8');
}
$name = clean_line($data['name'] ?? '', 120);
$mobile = preg_replace('/\D+/', '', (string)($data['mobile'] ?? '')) ?? '';
$city = clean_line($data['city'] ?? '', 120);
$interest = clean_line($data['interest'] ?? '', 120);
$email = clean_line($data['email'] ?? '', 190);
$message = trim((string)($data['message'] ?? ''));
$message = mb_substr(preg_replace('/\r\n?/', "\n", $message) ?? '', 0, 3000, 'UTF-8');
$source = clean_line($data['source'] ?? 'Website Enquiry', 80);

$allowedInterests = [
    'Child Education Planning','Marriage Planning','Retirement / Pension','Money-Back Plan',
    'Endowment / Savings','Term Insurance','Whole Life Plan','Other'
];
if (mb_strlen($name, 'UTF-8') < 2) respond(422, ['success' => false, 'message' => 'Please enter your full name.']);
if (strlen($mobile) === 12 && str_starts_with($mobile, '91')) $mobile = substr($mobile, 2);
if (strlen($mobile) === 11 && str_starts_with($mobile, '0')) $mobile = substr($mobile, 1);
if (!preg_match('/^[6-9][0-9]{9}$/', $mobile)) respond(422, ['success' => false, 'message' => 'Please enter a valid Indian mobile number.']);
if ($city === '') respond(422, ['success' => false, 'message' => 'Please enter your city.']);
if (!in_array($interest, $allowedInterests, true)) respond(422, ['success' => false, 'message' => 'Please select a valid enquiry category.']);
if ($email !== '' && !filter_var($email, FILTER_VALIDATE_EMAIL)) respond(422, ['success' => false, 'message' => 'Please enter a valid email address or leave it blank.']);

$config = require __DIR__ . '/mail-config.php';
$recipient = (string)($config['recipient'] ?? '');
if (!filter_var($recipient, FILTER_VALIDATE_EMAIL)) respond(500, ['success' => false, 'message' => 'Email recipient is not configured correctly.']);
$host = preg_replace('/[^a-zA-Z0-9.-]/', '', (string)($_SERVER['HTTP_HOST'] ?? '')) ?: 'localhost';
$sender = (string)($config['sender_email'] ?? '');
if (!filter_var($sender, FILTER_VALIDATE_EMAIL)) $sender = 'website@' . $host;
$senderName = str_replace(['\\', '"'], ['', "'"], (string)($config['sender_name'] ?? 'Website Enquiry'));
$subjectPrefix = clean_line($config['subject_prefix'] ?? 'New Website Enquiry', 80);
$subject = $subjectPrefix . ' — ' . $source;

$ip = (string)($_SERVER['REMOTE_ADDR'] ?? 'unknown');
$when = date('Y-m-d H:i:s') . ' (' . date_default_timezone_get() . ')';
$body = "A new enquiry was submitted on the LIC advisor website.\n\n";
$body .= "Name: {$name}\nMobile: +91 {$mobile}\nCity: {$city}\nInterested in: {$interest}\n";
$body .= 'Email: ' . ($email !== '' ? $email : 'Not provided') . "\n";
$body .= "Lead source: {$source}\nSubmitted at: {$when}\n";
$body .= 'Message: ' . ($message !== '' ? $message : 'No message provided') . "\n\n";
$body .= "This notification was generated by the Aman Bhardwaj LIC advisor website.\n";
$headers = [];
$headers[] = 'MIME-Version: 1.0';
$headers[] = 'Content-Type: text/plain; charset=UTF-8';
$headers[] = 'From: ' . $senderName . ' <' . $sender . '>';
if ($email !== '') $headers[] = 'Reply-To: ' . $email;
$headers[] = 'X-Mailer: PHP/' . PHP_VERSION;

// Do not log personal form data. Return success only when the host accepts the message.
$sent = @mail($recipient, '=?UTF-8?B?' . base64_encode($subject) . '?=', $body, implode("\r\n", $headers));
if (!$sent) {
    error_log('LIC website enquiry mail() failed; source=' . $source . '; host=' . $host . '; ip=' . $ip);
    respond(502, ['success' => false, 'message' => 'Email server ne enquiry accept nahi ki. Hosting email/SMTP configuration check karein, phir dobara try karein.']);
}
respond(200, ['success' => true, 'message' => 'Your enquiry has been accepted for email delivery.']);
